export function getDefaultImageForVertical(vertical = 'salon') {
  return DEFAULT_VERTICAL_IMAGES[vertical] || DEFAULT_VERTICAL_IMAGES.salon;
}

/**
 * Finds the best matching Unsplash image URL based on service name, query, and category
 */
export function findCatalogImage(name = '', categoryOrQuery = '', vertical = 'salon') {
  const catalog = vertical === 'cafe'
    ? DISH_IMAGE_CATALOG
    : vertical === 'clinic'
      ? CLINIC_IMAGE_CATALOG
      : SERVICE_IMAGE_CATALOG;

  const target = `${name} ${categoryOrQuery}`.toLowerCase().trim();
  if (!target) return getDefaultImageForVertical(vertical);

  // 1. Direct keyword match
  for (const entry of catalog) {
    for (const kw of entry.keywords) {
      if (target.includes(kw)) {
        return entry.url;
      }
    }
  }

  // 2. Token overlap match (token length >= 4)
  const tokens = [...new Set(target.split(/\s+/))].filter(t => t.length >= 4);
  for (const entry of catalog) {
    for (const kw of entry.keywords) {
      for (const token of tokens) {
        if (kw.includes(token)) {
          return entry.url;
        }
      }
    }
  }

  // 3. Fallback to vertical default
  return getDefaultImageForVertical(vertical);
}
